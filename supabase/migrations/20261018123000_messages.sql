-- =====================================================================
-- AGAKAI - MESSAGES MODULE & RLS
-- Allows senior citizens to exchange messages with peers and OSCA staff.
-- Enforces row-level security so seniors only access their own messages.
-- =====================================================================

-- 1. Table: public.messages
CREATE TABLE IF NOT EXISTS public.messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id integer NOT NULL REFERENCES public."user"(id) ON DELETE CASCADE,
  receiver_id integer NOT NULL REFERENCES public."user"(id) ON DELETE CASCADE,
  message text NOT NULL CHECK (btrim(message) <> ''),
  created_at timestamp with time zone DEFAULT now()
);

-- 2. Indexes for fast lookup of chat threads and recent messages
CREATE INDEX IF NOT EXISTS idx_messages_sender_id ON public.messages(sender_id);
CREATE INDEX IF NOT EXISTS idx_messages_receiver_id ON public.messages(receiver_id);
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON public.messages(sender_id, receiver_id, created_at);

-- 3. Row Level Security (RLS)
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "messages_select_own" ON public.messages;
DROP POLICY IF EXISTS "messages_insert_own" ON public.messages;

-- Seniors can only view messages where they are sender or receiver
CREATE POLICY "messages_select_own" ON public.messages
  FOR SELECT TO authenticated
  USING (
    sender_id IN (SELECT id FROM public."user" WHERE auth_user_id = (SELECT auth.uid()))
    OR
    receiver_id IN (SELECT id FROM public."user" WHERE auth_user_id = (SELECT auth.uid()))
  );

-- Seniors can only send messages as themselves
CREATE POLICY "messages_insert_own" ON public.messages
  FOR INSERT TO authenticated
  WITH CHECK (
    sender_id IN (SELECT id FROM public."user" WHERE auth_user_id = (SELECT auth.uid()))
  );

GRANT SELECT, INSERT ON TABLE public.messages TO authenticated;

-- 4. Enable Supabase Realtime for instant message updates
DO $$
BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
EXCEPTION
  WHEN OTHERS THEN NULL;
END $$;

-- 5. Safe contact lookup function
-- Allows authenticated seniors to list contacts without exposing user_notes or credentials
CREATE OR REPLACE FUNCTION public.get_chat_contacts()
RETURNS TABLE (
  id integer,
  name text,
  city text,
  address text,
  gender text
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT u.id, u.name, coalesce(u.city, 'Lapu-Lapu City') AS city, u.address, u.gender
  FROM public."user" u
  WHERE u.id <> coalesce((SELECT id FROM public."user" WHERE auth_user_id = auth.uid()), -1);
$$;

REVOKE ALL ON FUNCTION public.get_chat_contacts() FROM public, anon;
GRANT EXECUTE ON FUNCTION public.get_chat_contacts() TO authenticated;
